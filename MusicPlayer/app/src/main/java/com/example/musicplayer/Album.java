package com.example.musicplayer;

public class Album {

    String name;
    String artist;
    String albumId;
    String albumArt;

    public Album(String name, String artist, String albumId, String albumArt){
        this.name = name;
        this.artist = artist;
        this.albumId = albumId;
        this.albumArt = albumArt;
    }

}
